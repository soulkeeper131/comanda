/**
 * Проверка на имейл адрес. До 254 знака (RFC 5321) и без знаците, които
 * парсерите на адреси тълкуват като списък или име (`,;:<>()"[]\`) — иначе
 * „a,a,…@b.c" минава проверката и после бави изпращането с секунди.
 * Регексът е линеен: етикетите на домейна не съдържат точка, затова няма
 * двусмислено разделяне и връщане назад.
 */
const EMAIL = /^[^\s@,;:<>()"[\]\\]+@[^\s@,;:<>()"[\]\\.]+(?:\.[^\s@,;:<>()"[\]\\.]+)+$/;

export const MAX_EMAIL_LENGTH = 254;

export function isValidEmail(value: unknown): value is string {
  return typeof value === "string" && value.length <= MAX_EMAIL_LENGTH && EMAIL.test(value);
}
